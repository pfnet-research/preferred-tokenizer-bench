def example(row, number):
    ids, pieces, decoded = row['token_ids'], row['tokens'], row['decoded_tokens']
    if not ids or not (len(ids) == len(pieces) == len(decoded)):
        raise ValueError('token representation arrays have different lengths')
    available = row.get('ids_available', True)
    if available:
        if not all(isinstance(value, int) and not isinstance(value, bool) and value >= 0 for value in ids):
            raise ValueError('invalid token ID')
        if row['roundtrip_exact'] is not (row['text'] == row['decoded_text']):
            raise ValueError('roundtrip flag disagrees with original/full decoded text')
    elif not (all(value is None for value in ids + decoded) and row['decoded_text'] is None and row['roundtrip_exact'] is None):
        raise ValueError('unavailable IDs/decoder must be explicitly null')
    if not all(isinstance(value, str) for value in pieces) or available and not all(isinstance(value, str) for value in decoded):
        raise ValueError('token representations must be strings')
    equality = ('yes' if row['roundtrip_exact'] else 'NO') if available else '検証不可（decoderなし）'
    lines = [f"## {number}. {escape(row['id'])}", '', f"{escape(row['collection'])} · {len(ids):,} tokens · 全列decode一致: **{equality}**", '', '### 入力', '', quote(row['text']), '', '### Token view', '']
    if row.get('boundaries_approximate'):
        lines.extend(['**近似境界（実token IDなし・公式tokenizerとの同一性未保証）**', ''])
    if row.get('measurement_context'):
        lines.extend([escape(row['measurement_context']), ''])
    if row.get('character_measurement'):
        measurement = row['character_measurement']
        lines.extend([f"文字集合の判定はSOH-prefix条件で **{measurement['measured_token_count']} tokens**。この表示の単独入力とは測定文脈が異なります。", ''])
    piece_format = row.get('piece_format', 'native_vocabulary_piece')
    lines.append(' '.join(token_view(readable_piece(piece, single, piece_format)) for piece, single in zip(pieces, decoded)))
    lines.extend(['', '<details>', '<summary>Exact IDs / raw pieces / 個別decode</summary>', ''])
    lines.append(exact_tokens(ids, pieces, decoded))
    lines.extend(['', '</details>', '', '### 全token列のdecode', '', quote(row['decoded_text']) if available else '利用できません。原文との一致検証はしていません。', ''])
    return '\n'.join(lines)


def load_artifact(root, relative):
    if Path(relative).is_absolute() or '..' in Path(relative).parts or not re.fullmatch(r'[A-Za-z0-9_./-]+', relative):
        raise ValueError('artifact path must be relative within results')
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or path.suffix != '.json':
        raise ValueError('artifact path must be a JSON file within results')
    return json.loads(path.read_text(encoding='utf-8'))


def generate(root, readme, page_size=20):
    index = load_artifact(root, 'index.json')
    if index['schema_version'] != 1 or not 1 <= page_size <= 25:
        raise ValueError('unsupported schema or page size')
    corpus = index['corpus']
    records = []
    summaries = {}
    selection = None
    corpus_counts = None
    pending = []
    for tokenizer in index['tokenizers']:
        slug = tokenizer['slug']
        if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9_-]*', slug):
            raise ValueError('unsafe tokenizer slug')
        summary = load_artifact(root, tokenizer['summary_path'])
        summaries[slug] = summary
        samples = load_artifact(root, tokenizer['examples_path'])
        if samples.get('corpus_sha256', corpus['sha256']) != corpus['sha256']:
            raise ValueError('examples use a different corpus snapshot')
        if summary.get('corpus', {}).get('sha256', corpus['sha256']) != corpus['sha256']:
            raise ValueError('summary uses a different corpus snapshot')
        docs = [dict(row, piece_format=row.get('piece_format', samples.get('piece_format', 'native_vocabulary_piece'))) for row in samples['documents']]
        if not 1 <= len(docs) <= 350 or len({row['id'] for row in docs}) != len(docs):
            raise ValueError('expected at most 350 unique shared examples')
        selected = [(row['id'], row['collection'], row['text']) for row in docs]
        fingerprint = hashlib.sha256(json.dumps(selected, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()
        current = (samples['seed'], samples['selection_sha256'], fingerprint)
        if selection is not None and selection != current:
            raise ValueError('tokenizers do not share exactly the same sample selection')
        selection = current
        metrics = summary['metrics']
        sample_exact = sum(row['roundtrip_exact'] is True for row in docs)
        sample_nonexact = sum(row['roundtrip_exact'] is False for row in docs)
        sample_unavailable = len(docs) - sample_exact - sample_nonexact
        sample_fidelity = f'{sample_exact}/{len(docs)}一致・{sample_nonexact}非一致・{sample_unavailable}検証不可'
        counts = (metrics['characters'], metrics['utf8_bytes'])
        if corpus_counts is not None and corpus_counts != counts:
            raise ValueError('tokenizers were scored on different corpus totals')
        corpus_counts = counts
        if metrics['tokens'] <= 0:
            raise ValueError('invalid full-corpus token count')
        for field in ('chars_per_token', 'bytes_per_token'):
            if not isinstance(metrics[field], (int, float)) or not math.isfinite(metrics[field]) or metrics[field] <= 0:
                raise ValueError('invalid full-corpus metric')
        batches, current, size = [], [], 0
        for position, row in enumerate(docs, 1):
            rendered = example(row, position)
            needed = len(rendered.encode())
            if current and (len(current) >= page_size or size + needed > 800_000):
                batches.append(current)
                current, size = [], 0
            current.append((position, rendered))
            size += needed
        if current:
            batches.append(current)
        for page, batch in enumerate(batches, 1):
            content = [GENERATED, '', '# ' + escape(tokenizer.get('display_name', tokenizer['model_id'])) + f' — samples {page}', '', '[概要・内訳](README.md) · [ランキング](../../../README.md)', '', PAGE_NOTES, '']
            turns = []
            if page > 1:
                turns.append(f'[前の文書](part-{page-1:03d}.md)')
            if page < len(batches):
                turns.append(f'[次の文書](part-{page+1:03d}.md)')
            content[6:6] = [' · '.join(turns), '']
            content.extend(rendered for _, rendered in batch)
            pending.append((root / 'pages' / slug / f'part-{page:03d}.md', '\n'.join(content)))
        vocab = vocabulary_cell(tokenizer)
        navigation = ' · '.join(f'[{batch[0][0]}–{batch[-1][0]}](part-{page:03d}.md)' for page, batch in enumerate(batches, 1))
        content = [
            '# ' + escape(tokenizer.get('display_name', tokenizer['model_id'])), '',
            '[ランキング](../../../README.md)', '',
            f'**[共通{len(docs)}例のtoken表示を見る](part-001.md)**', '', navigation, '',
            f"データ全体（文字集合を含む）: {corpus['documents']:,}文書 / 目標 {corpus['target_documents']:,}文書 · **{'complete' if corpus['complete'] else 'PARTIAL'}**", '',
            f"ランキング対象（文字集合を除く）: {metrics.get('documents', 'unknown')}文書。", '',
            '## 全コーパスの結果', '', metric_table({'全体': metrics}), '',
            '同一コーパスのUTF-8総bytes / 総tokens（micro）で比較します。LLMの回答品質を測る指標ではありません。', '',
            '<details>', '<summary>出典・リビジョン・再現条件</summary>', '',
            f"Artifact: {literal(tokenizer['model_id'])} · Revision: {literal(tokenizer['revision'])} · 語彙数: {vocab}", '',
            VOCAB_NOTES, '',
            f"Corpus SHA-256: {literal(corpus['sha256'])}", '',
            *(['本文・ID・順序を保ったmetadataのみの改訂で、再評価は行っていません。計測時と配布版のhash対応は[同一性の記録](../../corpus-metadata-revision.json)にまとめています。', ''] if summary.get('corpus_metadata_revision') else []),
            f"Selection SHA-256: {literal(samples['selection_sha256'])} · seed: {literal(samples['seed'])}", '',
            '</details>', '',
            '<details>', '<summary>全言語・ジャンルの集合別内訳</summary>', '',
            '各集合内の総数から求めたmicro比率です。言語比率のmacro平均ではありません。', '',
            metric_table(summary.get('collections', {})), '', '</details>', '',
            '## 言語・評価群別', '', metric_table(summary.get('groups', {})), '',
            '## 文字集合の単一token率', '',
            '| 集合 | 単一token | 全体 | 割合 | 不安定prefix |',
            '| --- | ---: | ---: | ---: | ---: |',
        ]
        for label, coverage in summary.get('character_coverage', {}).items():
            content.append(f"| {escape(label)} | {coverage['one_token']:,} | {coverage['total']:,} | {coverage['ratio']:.2%} | {coverage.get('prefix_not_stable', 0):,} |")
        content.extend(['', '## 復元の忠実性', '', '共通sample: ' + sample_fidelity, '', 'Bytes/tokenが高いことは、入力を忠実に復元できることやモデル品質を保証しません。', '非一致にはtokenizer固有の正規化なども含まれるため、非一致だけで実装の故障とは断定しません。'])
        labels = {'documents': '全体の測定文書', 'roundtrip_exact_documents': '全列decode一致文書', 'roundtrip_nonexact_documents': '全列decode非一致文書', 'unknown_tokens': 'UNK token数', 'documents_with_unknown_tokens': 'UNKを含む文書', 'decode_unavailable_documents': 'decode検証不可の文書'}
        for key, value in summary.get('fidelity', {}).items():
            content.append(f'- {escape(labels.get(key, key))}: {value:,}')
        if summary.get('fidelity_note'):
            content.extend(['', escape(summary['fidelity_note'])])
        backend = summary.get('tokenizer', {})
        if not tokenizer.get('ranking_eligible', True):
            content.extend(['', '**参考値・公式順位の対象外**', '', escape(tokenizer.get('ranking_note', summary.get('ranking_note', '非公式・近似backend。公式モデルtokenizerとの同一性や復元を保証しません。')))])
            if backend.get('message_overhead') is not None:
                content.extend(['', f"メッセージframe overhead: {backend['message_overhead']}（本文token数とは別）。"])
            for note in backend.get('notes', []):
                content.append('- ' + escape(note))
        content.extend(['', '文字集合の被覆率は文章の分割効率と別に表示し、総合順位には混ぜません。', '', '符号化条件: ' + escape(summary.get('encoding_policy', 'See numerical metadata.')), '', '文字集合の測定条件: ' + escape(summary.get('character_metric', 'See numerical metadata.')), '', '## 共通sampleのtoken表示', '', f"{len(docs)}文書。全tokenizerで同一ID・同一入力・同一順序を使用し、閲覧sampleから全体scoreを計算しません。", '', f"Selection SHA-256: {literal(samples['selection_sha256'])} · seed: {literal(samples['seed'])}", '', f"[数値JSON](../../{tokenizer['summary_path']}) · [共通sample JSON](../../{tokenizer['examples_path']})", ''])
        for page, batch in enumerate(batches, 1):
            first, last = batch[0][0], batch[-1][0]
            content.append(f'- [文書 {first}–{last}](part-{page:03d}.md)')
        content.extend(['', 'tokenizer piece、個別tokenのdecode、全token列のdecodeを分けて表示します。', 'byte fallback、正規化や特殊tokenの影響により、それぞれが入力の文字範囲を示すとは限りません。', '全列decodeと入力の一致を文書ごとに確認できます。', ''])
        pending.append((root / 'pages' / slug / 'README.md', '\n'.join(content)))
        records.append((tokenizer, metrics))
    if not records:
        raise ValueError('no measured tokenizers')
    records.sort(key=lambda row: (-row[1]['bytes_per_token'], row[0]['model_id'], row[0]['revision']))
    ranking = ['## ランキング', '', '[日本語カテゴリ別](#日本語カテゴリ別) · [英語カテゴリ別](#英語カテゴリ別) · [他言語tier別](#他言語のtier別) · [文字集合率](#日本語文字集合の単一token率)', '', '全コーパスの **Bytes/token（総UTF-8 bytes / 総tokens）降順**。同じ入力集合なら総token数の昇順と一致します。', '文字集合の単一token率は別指標です。', f"データ全体（文字集合を含む） {corpus['documents']:,}文書 / 目標 {corpus['target_documents']:,}文書 · **{'complete' if corpus['complete'] else 'PARTIAL'}**。", f"順位は文字集合を除く{records[0][1].get('documents', 'unknown')}文書で測定。共通sampleは最大350文書の閲覧用です。", '圧縮値は復元の忠実性を保証しません。正規化による非一致もあり、詳細の復元/UNK集計と併せて確認してください。']
    ranking.extend(['', VOCAB_NOTES])
    for eligible, heading in [(True, ''), (False, '### 参考値（公式順位の対象外）')]:
        selected = [record for record in records if record[0].get('ranking_eligible', True) is eligible]
        if not selected:
            continue
        ranking.extend(['', heading, '', '| 順位 | Tokenizer・詳細 | 語彙数 | Tokens ↓ | Chars/token ↑ | Bytes/token ↑ |', '| ---: | --- | ---: | ---: | ---: | ---: |'])
        for rank, (tokenizer, metrics) in enumerate(selected, 1):
            place = str(rank) if eligible else '参考'
            ranking.append(f"| {place} | [{escape(tokenizer.get('display_name', tokenizer['model_id']))}](results/pages/{tokenizer['slug']}/README.md) | {vocabulary_cell(tokenizer)} | {metrics['tokens']:,} | {metrics['chars_per_token']:.4f} | {metrics['bytes_per_token']:.4f} |")
    ranking.extend(score_breakdowns([(record[0], summaries[record[0]['slug']]) for record in records]))
    block = START + '\n' + '\n'.join(ranking) + '\n' + END
    previous = readme.read_text(encoding='utf-8')
    if START in previous or END in previous:
        if previous.count(START) != 1 or previous.count(END) != 1:
            raise ValueError('invalid README ranking markers')
        updated = previous[:previous.index(START)] + block + previous[previous.index(END) + len(END):]
    else:
        position = previous.find('\n## ')
        if position < 0:
            position = previous.find('\n')
        updated = previous[:position] + '\n\n' + block + '\n' + previous[position:]
    # Validate every tokenizer/sample before writing any output.
    for path, content in pending:
        if len(content.encode()) > 1024 * 1024:
            raise ValueError('report page exceeds 1 MiB; use a smaller --page-size')
    for path, content in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
    expected = {path for path, _ in pending}
    for tokenizer in index['tokenizers']:
        for path in (root / 'pages' / tokenizer['slug']).glob('part-*.md'):
            if path not in expected and path.read_text(encoding='utf-8').startswith(GENERATED):
                path.unlink()
    readme.write_text(updated, encoding='utf-8')
    return len(records), len(pending)


