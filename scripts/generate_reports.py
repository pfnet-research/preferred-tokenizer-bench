def escape(text):
    """Prevent Markdown and GitHub's later mention/autolink filters."""
    parts = []
    hex_run = 0
    for char in str(text):
        hex_run = hex_run + 1 if char in string.hexdigits else 0
        value = f'&#{ord(char)};' if char in string.punctuation or char.isspace() or ord(char) < 32 else html.escape(char)
        parts.append(f'<span>{value}</span>' if char in '@#.:$' or hex_run > 0 and hex_run % 6 == 0 else value)
    return ''.join(parts)


def quote(text):
    """Keep lines/indentation while allowing ordinary prose to wrap."""
    lines = []
    original = text.split('\n')
    for number, line in enumerate(original):
        shown = []
        column = 0
        leading = True
        for position, char in enumerate(line):
            if char == '\t':
                width = 4 - column % 4
                shown.append('\u00a0' * width if leading else '\u00a0' * (width - 1) + ' ')
                column += width
            else:
                repeated_space = position > 0 and line[position - 1] == ' '
                shown.append('\u00a0' if char == ' ' and (leading or repeated_space) else char)
                column += 1
            leading = leading and char.isspace()
        suffix = '\\' if line and number + 1 < len(original) and original[number + 1] else ''
        body = escape(''.join(shown)) + suffix
        lines.append('> ' + body if body else '>')
    return '\n'.join(lines)


def literal(value):
    """A JSON string exposes spaces, newlines, tabs and special-token spelling."""
    return '<code>' + escape(json.dumps(value, ensure_ascii=False)) + '</code>'


def token_view(piece):
    """Visible whitespace without suggesting that pieces are source offsets."""
    shown = ''.join({' ': '␠', '\n': '↵', '\t': '⇥', '\r': '␍', '\u00a0': '⍽'}.get(char, char) for char in piece) or '∅'
    # A long individual piece can wrap without adding a character to its text.
    return '<code>' + '<br>'.join(escape(shown[i:i + 48]) for i in range(0, len(shown), 48)) + '</code>'


def readable_piece(piece, decoded, piece_format):
    if isinstance(decoded, str) and decoded and '\ufffd' not in decoded:
        return decoded
    if piece_format == 'hex_bytes':
        if len(piece) % 2 or not re.fullmatch('[0-9a-fA-F]*', piece):
            raise ValueError('invalid explicit hex-byte piece')
        return '<bytes: ' + (' '.join(piece[i:i + 2].upper() for i in range(0, len(piece), 2)) or 'empty') + '>'
    return piece


def exact_tokens(ids, pieces, decoded):
    rows = ['position | token ID | raw piece (JSON string) | individual decode (JSON string)']
    for position, values in enumerate(zip(ids, pieces, decoded), 1):
        rows.append(f'{position} | ' + ' | '.join(json.dumps(value, ensure_ascii=False) for value in values))
    text = '\n'.join(rows)
    fence = '`' * max(3, 1 + max((len(run) for run in re.findall(r'`+', text)), default=0))
    return fence + 'text\n' + text + '\n' + fence


def metric_table(metrics):
    rows = ['| 対象 | Tokens ↓ | Chars/token ↑ | Bytes/token ↑ |', '| --- | ---: | ---: | ---: |']
    for label, values in metrics.items():
        rows.append(f"| {escape(label)} | {values['tokens']:,} | {values['chars_per_token']:.4f} | {values['bytes_per_token']:.4f} |")
    return '\n'.join(rows)



def vocabulary_cell(tokenizer):
    size = tokenizer.get('vocab_size')
    if size is None:
        return '—'
    if type(size) is not int or size <= 0:
        raise ValueError('invalid vocabulary size')
    return f'{size:,}'


def comparison_table(records, columns, coverage=False):
    """Sort each comparison by its exact, equal-weight arithmetic mean."""
    ranked = []
    for tokenizer, summary in records:
        ratios = []
        for _, section, key in columns:
            values = summary.get(section, {}).get(key)
            if values is None:
                ratios.append(None)
                continue
            numerator, denominator = ('one_token', 'total') if coverage else ('utf8_bytes', 'tokens')
            top, bottom = values.get(numerator), values.get(denominator)
            if top is None or bottom is None:
                ratios.append(None)
                continue
            if any(type(value) is not int or value < 0 for value in (top, bottom)) or bottom == 0:
                raise ValueError('invalid comparison counts')
            if coverage and top > bottom:
                raise ValueError('single-token coverage exceeds total')
            ratios.append(Fraction(top, bottom))
        mean = sum(ratios, Fraction()) / len(ratios) if ratios and all(r is not None for r in ratios) else None
        ranked.append((tokenizer, ratios, mean))
    ranked.sort(key=lambda row: (row[2] is None, -row[2] if row[2] is not None else 0, row[0]['slug']))
    lines = []
    for eligible, label in [(True, '正式tokenizer'), (False, '参考値（公式順位の対象外）')]:
        selected = [row for row in ranked if row[0].get('ranking_eligible', True) is eligible]
        if not selected:
            continue
        lines.extend(['', '**' + label + '**', '',
                      '| Tokenizer・詳細 | 語彙数 | 平均 ↑ | ' + ' | '.join(name for name, _, _ in columns) + ' |',
                      '| --- | ---: | ---: | ' + ' | '.join('---:' for _ in columns) + ' |'])
        for tokenizer, ratios, mean in selected:
            def display(value):
                if value is None:
                    return '—'
                return f'{float(value):.2%}' if coverage else f'{float(value):.4f}'
            cells = [vocabulary_cell(tokenizer), display(mean)] + [display(value) for value in ratios]
            name = escape(tokenizer.get('display_name', tokenizer['model_id']))
            lines.append(f"| [{name}](results/pages/{tokenizer['slug']}/README.md) | " + ' | '.join(cells) + ' |')
    return lines


